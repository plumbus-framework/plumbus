/** Generate login page for the configured auth transport */
export function generateLoginPage(config?: NextjsTemplateConfig): GeneratedFile {
  return config?.authTransport === 'session'
    ? generateSessionLoginPage()
    : generateBearerLoginPage();
}

/** Generate a signup page (bearer transport only) */
export function generateSignupPage(): GeneratedFile {
  return {
    path: 'app/signup/page.tsx',
    content: `"use client";

import { useState } from "react";

export default function SignupPage() {
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  const handleSubmit = async (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    setLoading(true);
    setError(null);
    const formData = new FormData(e.currentTarget);
    try {
      const response = await fetch(
        (process.env["NEXT_PUBLIC_API_BASE_URL"] ?? "") + "/api/auth/signup",
        {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            email: formData.get("email") as string,
            password: formData.get("password") as string,
            name: formData.get("name") as string,
          }),
        },
      );
      if (!response.ok) {
        const body = await response.json().catch(() => ({}));
        throw new Error(body.message ?? "Signup failed");
      }
      window.location.href = "/login";
    } catch (err) {
      setError(err instanceof Error ? err.message : "Signup failed");
    } finally {
      setLoading(false);
    }
  };

  return (
    <main>
      <h1>Sign Up</h1>
      <form onSubmit={handleSubmit}>
        <label htmlFor="name">Name</label>
        <input id="name" name="name" type="text" required />
        <label htmlFor="email">Email</label>
        <input id="email" name="email" type="email" required />
        <label htmlFor="password">Password</label>
        <input id="password" name="password" type="password" required />
        <button type="submit" disabled={loading}>
          {loading ? "Creating account..." : "Sign up"}
        </button>
      </form>
      {error && <p role="alert">{error}</p>}
      <p>Already have an account? <a href="/login">Log in</a></p>
    </main>
  );
}
`,
  };
}

/** Generate the complete Next.js template file set */
export function generateNextjsTemplate(
  config: NextjsTemplateConfig,
  _capabilities?: CapabilityContract[],
): GeneratedFile[] {
  const files: GeneratedFile[] = [
    generatePackageJson(config),
    generateTsConfig(),
    generateGlobalsCss(),
    generatePostcssConfig(),
    generateLayout(config),
    generateHomePage(config),
    generateEnvLocal(config),
    generateErrorBoundary(),
    generateLoadingComponent(),
    generateProxy(config),
    ...generatePlaceholderFiles(),
  ];

  if (config.auth !== false) {
    files.push(generateAuthProvider(config));
    files.push(generateLoginPage(config));
    if (config.authTransport === 'session') {
      files.push(generateSessionLoginErrorPage());
    }
    if (config.authTransport !== 'session') {
      files.push(generateSignupPage());
    }
  }

  return files;
}

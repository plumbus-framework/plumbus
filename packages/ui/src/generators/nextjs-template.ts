// ── Next.js Project Template Generator ──
// Generates a Next.js project scaffold with Plumbus auth integration,
// generated client imports, and example pages wired to capabilities.

import type { CapabilityContract } from '@plumbus/core';

import type { AuthTransport } from './auth-generator.js';

export interface NextjsTemplateConfig {
  /** Application name */
  appName: string;
  /** Whether to include auth wiring */
  auth?: boolean;
  /** Auth credential transport */
  authTransport?: AuthTransport;
  /** Base URL for API calls. Required for `.env.local` — no localhost port default. */
  apiBaseUrl?: string;
}

// ── Helpers ──

function toPascalCase(str: string): string {
  return str.replace(/(^|[-_ ])(\w)/g, (_, _sep: string, c: string) => c.toUpperCase());
}

function toKebabCase(str: string): string {
  return str
    .replace(/([a-z])([A-Z])/g, '$1-$2')
    .replace(/[\s_]+/g, '-')
    .toLowerCase();
}

// ── File Generators ──

export interface GeneratedFile {
  path: string;
  content: string;
}

/** Generate package.json for the Next.js project */
export function generatePackageJson(config: NextjsTemplateConfig): GeneratedFile {
  const name = toKebabCase(config.appName);
  const content = JSON.stringify(
    {
      name,
      version: '0.1.0',
      private: true,
      scripts: {
        dev: 'next dev',
        build: 'next build',
        start: 'next start',
      },
      dependencies: {},
      devDependencies: {},
    },
    null,
    2,
  );

  return { path: 'package.json', content };
}

